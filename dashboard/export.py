"""Downloadable notes (PLAN M6c, docs/NOTEBOOK_DESIGN.md §6.3, §11): Markdown, Word and PDF from the same notebook the
page shows (dashboard/queries.notebook), so the files read like the screen.

  * One document order for all three formats: title and status, contents, each topic with its elements in spoken
    order (times in the margin of the page become [mm:ss] after each element), the topic's "Your additions" slot
    (filled by NOTEBOOK_DESIGN §13 later), its check-yourself question; while the lecture is live, the draft notes;
    then glossary, answers to the questions (at the end, so the questions can be tried first) and course info.
  * Paragraph text is built as runs (text, style) once, so bold leads and the first mention of each glossary term
    look the same everywhere.
  * PDF uses matplotlib's bundled DejaVu fonts (no download, full Unicode such as – “ ” → ≥ ✓).

Tested by tests/test_export.py (X-1).
"""

from __future__ import annotations

import io
import re
from datetime import datetime
from pathlib import Path

from agents.text import mmss
from dashboard.notebook_html import FALLBACK_NOTE

Run = tuple[str, str]           # (text, style): "" plain, "b" bold, "i" italic, "t" time (small, muted)


# ----------------------------------------------------------------------------------------------- shared structure
def paragraph_runs(el: dict) -> list[Run]:
    """A para's text: bold lead, sentences with the first mention of each glossary term in bold."""
    runs: list[Run] = [(f"{el['lead']}. ", "b")] if el.get("lead") else []
    pending = [t["term"] for t in el.get("terms", [])]
    text = " ".join(el.get("sentences", []))
    while pending:
        hits = [(m.start(), m.end(), term) for term in pending
                if (m := re.search(re.escape(term), text, re.I))]
        if not hits:
            break
        start, end, term = min(hits)
        runs += [(text[:start], ""), (text[start:end], "b")]
        text = text[end:]
        pending.remove(term)
    runs.append((text, ""))
    return [r for r in runs if r[0]]


def status_line(nb: dict) -> str:
    if nb["finished"]:
        return f"Finished lecture · {mmss(nb['said_until'])}"
    return (f"Live lecture: organised notes up to {mmss(nb['since'])}, draft notes up to {mmss(nb['reach'])} "
            f"(exported {datetime.now():%H:%M})")


def without_llm(topic: dict) -> bool:
    return topic.get("generator") == "fallback"


SOURCE_NOTE = ("Notes generated by EduStream from the lecture's transcript. Times [mm:ss] point to where each part "
               "was said. Text marked as background was not said in the lecture.")


def file_stem(title: str) -> str:
    return re.sub(r"[^A-Za-z0-9]+", "_", title).strip("_")[:60] or "lecture"


# ----------------------------------------------------------------------------------------------- Markdown
_MD_SPECIAL = re.compile(r"([\\`*_\[\]<>#|])")


def _md(text: str) -> str:
    return _MD_SPECIAL.sub(r"\\\1", text)


def _md_runs(runs: list[Run]) -> str:
    out = []
    for text, style in runs:
        t = _md(text)
        if style == "b" and t.strip():
            lead, core, trail = re.match(r"(\s*)(.*?)(\s*)$", t, re.S).groups()
            t = f"{lead}**{core}**{trail}"
        elif style == "i" and t.strip():
            t = f"*{t.strip()}*"
        out.append(t)
    return "".join(out)


def _md_code(code: str) -> list[str]:
    return ["```", code.replace("```", "`​``"), "```"]


def _md_element(el: dict) -> list[str]:
    k, when = el["kind"], f" *[{mmss(el['t'])}]*"
    if k == "para":
        lines = [_md_runs(paragraph_runs(el)) + when]
        if el.get("background"):
            lines += ["", f"> *Background (not from the lecture): {_md(el['background'])}*"]
        return lines
    if k == "example":
        lines = [f"> **Example{' · ' + _md(el['title']) if el.get('title') else ''}**{when}"]
        if el.get("sentences"):
            lines += [">", "> " + _md(" ".join(el["sentences"]))]
        if el.get("steps"):
            lines += [">"] + [f"> {i}. {_md(s)}" for i, s in enumerate(el["steps"], 1)]
        if el.get("code"):
            lines += [">"] + ["> " + line for line in _md_code(el["code"])]
        return lines
    if k == "steps":
        return [f"**{_md(el['lead'])}:**{when}", ""] + [f"{i}. {_md(s)}" for i, s in enumerate(el["items"], 1)]
    if k == "table":
        head = [f"**{_md(el['caption'])}**{when}", ""] if el.get("caption") else [when.strip(), ""]
        cells = lambda row: "| " + " | ".join(_md(c) for c in row) + " |"  # noqa: E731
        return head + [cells(el["columns"]), "|" + "---|" * len(el["columns"])] + [cells(r) for r in el["rows"]]
    if k == "code":
        return ([f"**{_md(el['caption'])}**{when}"] if el.get("caption") else [when.strip()]) + _md_code(el["code"])
    return [f"**Remember:** {_md(el['text'])}{when}"]


def to_markdown(nb: dict, title: str) -> str:
    lines = [f"# {_md(title)}", "", f"*{status_line(nb)}*", "", SOURCE_NOTE, ""]
    if nb["topics"]:
        lines += ["## Contents", ""] + [f"{t['n']}. {_md(t['title'])} ({mmss(t['start'])}–{mmss(t['end'])})"
                                        for t in nb["topics"]] + [""]
    for t in nb["topics"]:
        lines += [f"## {t['n']}. {_md(t['title'])}", "", f"*{mmss(t['start'])}–{mmss(t['end'])}*", ""]
        if without_llm(t):
            lines += [f"*{FALLBACK_NOTE}*", ""]
        for el in t["elements"]:
            lines += _md_element(el) + [""]
        if t.get("additions"):
            lines += ["### Your additions", ""]
            for el in t["additions"]:
                lines += _md_element(el) + [""]
        if t.get("question"):
            lines += [f"**Check yourself:** {_md(t['question'])}", ""]
    if not nb["finished"] and nb["drafts"]:
        lines += [f"## Live notes since {mmss(nb['since'])} (draft)", ""]
        for el in nb["drafts"]:
            lines += _md_element(el) + [""]
    lines += _md_tail(nb)
    return "\n".join(lines).rstrip() + "\n"


def _md_tail(nb: dict) -> list[str]:
    lines: list[str] = []
    if nb["glossary"]:
        lines += ["## Glossary", ""] + [f"- **{_md(g['term'])}**: {_md(g['definition'])}" for g in nb["glossary"]]
        lines.append("")
    answered = [t for t in nb["topics"] if t.get("question")]
    if answered:
        lines += ["## Answers to “Check yourself”", ""]
        lines += [f"{t['n']}. *{_md(t['question'])}* {_md(t.get('answer') or '')}" for t in answered] + [""]
    if nb["info"]:
        lines += ["## Course info", ""] + [f"- {_md(i['text'])}" for i in nb["info"]] + [""]
    return lines


# ----------------------------------------------------------------------------------------------- Word
def to_docx(nb: dict, title: str) -> bytes:
    from docx import Document
    from docx.shared import Pt, RGBColor

    muted, amber = RGBColor(0x6B, 0x72, 0x80), RGBColor(0xB4, 0x53, 0x09)
    doc = Document()
    doc.styles["Normal"].font.name = "Calibri"
    doc.styles["Normal"].font.size = Pt(11)
    doc.add_heading(title, level=0)
    p = doc.add_paragraph()
    r = p.add_run(status_line(nb))
    r.italic = True
    doc.add_paragraph(SOURCE_NOTE).runs[0].font.color.rgb = muted

    def runs_into(par, runs: list[Run]) -> None:
        for text, style in runs:
            run = par.add_run(text)
            run.bold = style == "b"
            run.italic = style == "i"
            if style == "t":
                run.font.size, run.font.color.rgb = Pt(8.5), muted

    def code_block(code: str, indent: float = 0.0) -> None:
        par = doc.add_paragraph()
        par.paragraph_format.left_indent = Pt(12 + indent)
        run = par.add_run(code)
        run.font.name, run.font.size = "Consolas", Pt(9.5)

    def numbered(items: list[str], indent: float = 0.0) -> None:
        for i, s in enumerate(items, 1):                  # numbered by hand: Word's list numbering runs on
            par = doc.add_paragraph()                     # across separate lists in python-docx
            par.paragraph_format.left_indent = Pt(18 + indent)
            par.paragraph_format.first_line_indent = Pt(-14)
            par.add_run(f"{i}. {s}")

    def element(el: dict) -> None:
        k, when = el["kind"], (f"  [{mmss(el['t'])}]", "t")
        if k == "para":
            runs_into(doc.add_paragraph(), paragraph_runs(el) + [when])
            if el.get("background"):
                par = doc.add_paragraph()
                par.paragraph_format.left_indent = Pt(12)
                runs_into(par, [(f"Background (not from the lecture): {el['background']}", "i")])
        elif k == "example":
            par = doc.add_paragraph()
            par.paragraph_format.left_indent = Pt(12)
            run = par.add_run(f"Example{' · ' + el['title'] if el.get('title') else ''}")
            run.bold, run.font.color.rgb = True, amber
            runs_into(par, [when])
            if el.get("sentences"):
                par = doc.add_paragraph(" ".join(el["sentences"]))
                par.paragraph_format.left_indent = Pt(12)
            if el.get("steps"):
                numbered(el["steps"], 12)
            if el.get("code"):
                code_block(el["code"], 12)
        elif k == "steps":
            runs_into(doc.add_paragraph(), [(f"{el['lead']}:", "b"), when])
            numbered(el["items"])
        elif k == "table":
            if el.get("caption"):
                runs_into(doc.add_paragraph(), [(el["caption"], "b"), when])
            table = doc.add_table(rows=1 + len(el["rows"]), cols=len(el["columns"]))
            table.style = "Table Grid"
            for j, c in enumerate(el["columns"]):
                table.cell(0, j).text = c
                for run in table.cell(0, j).paragraphs[0].runs:
                    run.bold = True
            for i, row in enumerate(el["rows"], 1):
                for j, c in enumerate(row):
                    table.cell(i, j).text = c
        elif k == "code":
            if el.get("caption"):
                runs_into(doc.add_paragraph(), [(el["caption"], "b"), when])
            code_block(el["code"])
        else:
            runs_into(doc.add_paragraph(), [("Remember: ", "b"), (el["text"], ""), when])

    if nb["topics"]:
        doc.add_heading("Contents", level=1)
        numbered([f"{t['title']} ({mmss(t['start'])}–{mmss(t['end'])})" for t in nb["topics"]])
    for t in nb["topics"]:
        doc.add_heading(f"{t['n']}. {t['title']}", level=1)
        runs_into(doc.add_paragraph(), [(f"{mmss(t['start'])}–{mmss(t['end'])}", "t")])
        if without_llm(t):
            runs_into(doc.add_paragraph(), [(FALLBACK_NOTE, "i")])
        for el in t["elements"]:
            element(el)
        if t.get("additions"):
            doc.add_heading("Your additions", level=2)
            for el in t["additions"]:
                element(el)
        if t.get("question"):
            runs_into(doc.add_paragraph(), [("Check yourself: ", "b"), (t["question"], "")])
    if not nb["finished"] and nb["drafts"]:
        doc.add_heading(f"Live notes since {mmss(nb['since'])} (draft)", level=1)
        for el in nb["drafts"]:
            element(el)
    if nb["glossary"]:
        doc.add_heading("Glossary", level=1)
        for g in nb["glossary"]:
            runs_into(doc.add_paragraph(), [(g["term"] + ": ", "b"), (g["definition"], "")])
    answered = [t for t in nb["topics"] if t.get("question")]
    if answered:
        doc.add_heading("Answers to “Check yourself”", level=1)
        for t in answered:
            runs_into(doc.add_paragraph(), [(f"{t['n']}. ", "b"), (t["question"] + " ", "i"), (t.get("answer") or "", "")])
    if nb["info"]:
        doc.add_heading("Course info", level=1)
        for i in nb["info"]:
            doc.add_paragraph(i["text"])
    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()


# ----------------------------------------------------------------------------------------------- PDF
def _pdf_md(text: str) -> str:
    """Escape fpdf2's markdown markers; break its link syntax "[x](y)" with a zero-width space (DejaVu has it)."""
    for marker in ("**", "__", "--", "~~"):
        text = text.replace(marker, "\\" + marker)
    return text.replace("](", "]\u200b(")


def _font_dir() -> Path:
    import matplotlib
    return Path(matplotlib.get_data_path()) / "fonts" / "ttf"


def to_pdf(nb: dict, title: str) -> bytes:
    from fpdf import FPDF
    from fpdf.enums import XPos, YPos

    class Doc(FPDF):
        def footer(self) -> None:
            self.set_y(-12)
            self.set_font("Sans", "", 8)
            self.set_text_color(110, 114, 128)
            self.cell(0, 6, f"{title} · page {self.page_no()}", align="C")

    pdf = Doc(format="A4")
    fonts = _font_dir()
    for style, name in (("", "DejaVuSans.ttf"), ("B", "DejaVuSans-Bold.ttf"), ("I", "DejaVuSans-Oblique.ttf"),
                        ("BI", "DejaVuSans-BoldOblique.ttf")):
        pdf.add_font("Sans", style, str(fonts / name))
    pdf.add_font("Mono", "", str(fonts / "DejaVuSansMono.ttf"))
    pdf.set_margins(18, 16, 18)
    pdf.set_auto_page_break(True, margin=16)
    pdf.add_page()
    width = pdf.w - pdf.l_margin - pdf.r_margin
    ink, muted, amber, line = (29, 36, 51), (107, 114, 128), (180, 83, 9), (190, 196, 206)

    def write_runs(runs: list[Run], size: float = 10.5, indent: float = 0.0) -> None:
        """One wrapped block in fpdf2's markdown (**bold**, __italic__). Writing run by run with write() split words
        across lines where a style changed near the end of a line ("Beca / use"). Times are italic here: markdown
        cannot change size or colour mid-line; a block made only of muted text is set small and grey instead."""
        quiet = all(style == "t" for _, style in runs)
        out = []
        for text, style in runs:
            mark = "" if quiet else {"b": "**", "i": "__", "t": "__"}.get(style, "")
            if mark and text.strip():
                lead, core, trail = re.match(r"(\s*)(.*?)(\s*)$", text, re.S).groups()
                out.append(f"{lead}{mark}{_pdf_md(core)}{mark}{trail}")
            else:
                out.append(_pdf_md(text))
        pdf.set_font("Sans", "", size - 1.5 if quiet else size)
        pdf.set_text_color(*(muted if quiet else ink))
        pdf.set_x(pdf.l_margin + indent)
        pdf.multi_cell(width - indent, 5.2, "".join(out), markdown=True, align="L", new_x=XPos.LMARGIN,
                       new_y=YPos.NEXT)
        pdf.set_text_color(*ink)
        pdf.ln(2)

    def heading(text: str, size: float, gap_before: float = 3.0) -> None:
        pdf.ln(gap_before)
        pdf.set_font("Sans", "B", size)
        pdf.set_text_color(*ink)
        pdf.multi_cell(width, size * 0.5, text, align="L", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        pdf.ln(1.5)

    def code_block(code: str, indent: float = 0.0) -> None:
        pdf.set_x(pdf.l_margin + indent)
        pdf.set_font("Mono", "", 9)
        pdf.set_fill_color(238, 241, 245)
        pdf.multi_cell(width - indent, 4.6, code, fill=True, align="L", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        pdf.ln(2)

    def numbered(items: list[str], indent: float = 0.0) -> None:
        for i, s in enumerate(items, 1):
            pdf.set_x(pdf.l_margin + indent + 2)
            pdf.set_font("Sans", "", 10.5)
            pdf.multi_cell(width - indent - 2, 5.2, f"{i}. {s}", align="L", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        pdf.ln(1.5)

    def element(el: dict) -> None:
        k, when = el["kind"], (f"  [{mmss(el['t'])}]", "t")
        if k == "para":
            write_runs(paragraph_runs(el) + [when])
            if el.get("background"):
                write_runs([(f"Background (not from the lecture): {el['background']}", "i")], 9.5, 6)
        elif k == "example":
            top = pdf.get_y()
            pdf.set_text_color(*amber)
            pdf.set_font("Sans", "B", 10)
            pdf.set_x(pdf.l_margin + 5)
            pdf.cell(0, 5.2, f"Example{' · ' + el['title'] if el.get('title') else ''}",
                     new_x=XPos.LMARGIN, new_y=YPos.NEXT)
            pdf.set_text_color(*ink)
            if el.get("sentences"):
                write_runs([(" ".join(el["sentences"]), ""), when], indent=5)
            else:
                pdf.ln(1)
            if el.get("steps"):
                numbered(el["steps"], 5)
            if el.get("code"):
                code_block(el["code"], 5)
            if pdf.get_y() > top:                         # a bar in the margin, as on the page
                pdf.set_draw_color(*amber)
                pdf.set_line_width(0.8)
                pdf.line(pdf.l_margin + 1, top, pdf.l_margin + 1, pdf.get_y() - 1)
                pdf.set_draw_color(*line)
                pdf.set_line_width(0.2)
        elif k == "steps":
            write_runs([(f"{el['lead']}:", "b"), when])
            numbered(el["items"])
        elif k == "table":
            if el.get("caption"):
                write_runs([(el["caption"], "b"), when])
            pdf.set_font("Sans", "", 9.5)
            pdf.set_draw_color(*line)
            pdf.set_line_width(0.2)
            with pdf.table(width=width, line_height=5, first_row_as_headings=True) as table:
                for row in [el["columns"]] + el["rows"]:
                    r = table.row()
                    for c in row:
                        r.cell(c)
            pdf.ln(2)
        elif k == "code":
            if el.get("caption"):
                write_runs([(el["caption"], "b"), when])
            code_block(el["code"])
        else:
            write_runs([("Remember: ", "b"), (el["text"], ""), when])

    pdf.set_font("Sans", "B", 18)
    pdf.multi_cell(width, 8, title, align="L", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    write_runs([(status_line(nb), "i")], 10)
    write_runs([(SOURCE_NOTE, "t")], 10)
    if nb["topics"]:
        heading("Contents", 13)
        numbered([f"{t['title']} ({mmss(t['start'])}–{mmss(t['end'])})" for t in nb["topics"]])
    for t in nb["topics"]:
        heading(f"{t['n']}. {t['title']}", 14, 5)
        write_runs([(f"{mmss(t['start'])}–{mmss(t['end'])}", "t")])
        if without_llm(t):
            write_runs([(FALLBACK_NOTE, "i")], 9.5)
        for el in t["elements"]:
            element(el)
        if t.get("additions"):
            heading("Your additions", 11.5)
            for el in t["additions"]:
                element(el)
        if t.get("question"):
            write_runs([("Check yourself: ", "b"), (t["question"], "")])
    if not nb["finished"] and nb["drafts"]:
        heading(f"Live notes since {mmss(nb['since'])} (draft)", 14, 5)
        for el in nb["drafts"]:
            element(el)
    if nb["glossary"]:
        heading("Glossary", 13, 5)
        for g in nb["glossary"]:
            write_runs([(g["term"] + ": ", "b"), (g["definition"], "")])
    answered = [t for t in nb["topics"] if t.get("question")]
    if answered:
        heading("Answers to “Check yourself”", 13, 5)
        for t in answered:
            write_runs([(f"{t['n']}. ", "b"), (t["question"] + " ", "i"), (t.get("answer") or "", "")])
    if nb["info"]:
        heading("Course info", 13, 5)
        for i in nb["info"]:
            write_runs([("• " + i["text"], "")])
    return bytes(pdf.output())


FORMATS = {
    "Markdown": ("md", "text/markdown", lambda nb, title: to_markdown(nb, title).encode("utf-8")),
    "Word": ("docx", "application/vnd.openxmlformats-officedocument.wordprocessingml.document", to_docx),
    "PDF": ("pdf", "application/pdf", to_pdf),
}
